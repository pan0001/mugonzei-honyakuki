using System.Collections.Concurrent;
using System.Text;
using System.Text.Json;
using Microsoft.Web.WebView2.Core;

namespace SteamVrTranslator;

internal static class GoogleSearchAiWebClientTests
{
    private const string Prompt = "Translate the synthetic fixture into Japanese.";
    private const string Success = "この列車は試験用です。";
    private sealed class Fixture(string answer, string? redirect = null, bool holdAnswer = false,
        string? fetchOnSubmit = null, bool checkScriptGuards = false)
    {
        internal readonly TaskCompletionSource Submitted = new(TaskCreationOptions.RunContinuationsAsynchronously);
        internal readonly ConcurrentQueue<string> Events = new();

        internal void Configure(CoreWebView2 core)
        {
            // All HTTP(S) requests, including redirects, are fulfilled here. blob: is the
            // in-memory test PNG generated by Chromium, not a network resource.
            core.AddWebResourceRequestedFilter("*", CoreWebView2WebResourceContext.All, CoreWebView2WebResourceRequestSourceKinds.All);
            core.WebResourceRequested += (_, args) =>
            {
                Uri uri = new(args.Request.Uri);
                if (uri.Scheme is not ("http" or "https")) return;
                string? body = null;
                if (uri.AbsoluteUri == GoogleSearchAiWebClient.EntryUrl)
                {
                    Events.Enqueue("open");
                    body = redirect is null ? Html() : "<script>location.replace(" + JsonSerializer.Serialize(redirect) + ")</script>";
                }
                else if (uri.AbsoluteUri == redirect && args.Request.Method == "GET")
                {
                    // Chromium may start a speculative, bodyless document request before it
                    // observes NavigationStarting.Cancel. Even if loaded, the destination
                    // has a fully operational image form that will report any sensitive use.
                    Events.Enqueue("redirect-get");
                    body = Html();
                }
                else if (uri.AbsolutePath.StartsWith("/fixture-event/", StringComparison.Ordinal))
                {
                    var name = uri.AbsolutePath["/fixture-event/".Length..];
                    Events.Enqueue(name);
                    if (name == "submit") Submitted.TrySetResult();
                }
                else if (uri.AbsolutePath == fetchOnSubmit)
                {
                    args.Response = core.Environment.CreateWebResourceResponse(null, 429, "Too Many Requests", "");
                    return;
                }
                else if (uri.AbsolutePath != "/favicon.ico") Events.Enqueue("unexpected-request:" + uri.GetLeftPart(UriPartial.Path));
                args.Response = body is null
                    ? core.Environment.CreateWebResourceResponse(null, 204, "No Content", "")
                    : core.Environment.CreateWebResourceResponse(new MemoryStream(Encoding.UTF8.GetBytes(body)), 200, "OK",
                        "Content-Type: text/html; charset=utf-8\r\nCache-Control: no-store");
            };
        }

        private string Html() => """
            <!doctype html><meta charset="UTF-8"><main><textarea aria-label="Ask anything"></textarea>
            <input type="file" accept="image/png"><button aria-label="Send">Send</button></main>
            <script>
            const main=document.querySelector('main'), editor=main.querySelector('textarea');
            const report=name=>fetch('/fixture-event/'+name);
            """ + (checkScriptGuards ? CheckGuards() : "") + """
            main.querySelector('input').onchange=e=>{
              const file=e.target.files[0], chip=document.createElement('div'), image=new Image();
              chip.setAttribute('role','button');chip.setAttribute('aria-label',file.name);
              image.src=URL.createObjectURL(file);chip.append(image);main.append(chip);
              report('png-'+file.size);
            };
            main.querySelector('button').onclick=async()=>{
              if(!editor.value.startsWith(
            """ + JsonSerializer.Serialize(Prompt) + """
              )) { await report('wrong-prompt'); return; }
              await report('submit');
            """ + (fetchOnSubmit is null ? "" : $"await fetch({JsonSerializer.Serialize(fetchOnSubmit)});") + (holdAnswer ? "return;" : "") + """
              const begin=editor.value.match(/MUBEGIN[a-f0-9]{12}/)[0], end=editor.value.match(/MUEND[a-f0-9]{12}/)[0];
              const section=document.createElement('section');
              for(const line of [begin,
            """ + JsonSerializer.Serialize(answer) + """
              ,end]){const p=document.createElement('p');p.textContent=line;section.append(p);}
              main.append(section);
            };
            </script>
            """;

        // Run the actual injected guard inside Chromium after a same-document address change;
        // an earlier host-side Source check alone cannot protect this interval.
        private static string CheckGuards()
        {
            const string touch = "(window.fixtureLeak=true,{state:'exposed'})";
            return "const old=location.href; history.replaceState(null,'','/search?q=ordinary');"
                + "const wrongPage=" + GoogleSearchAiWebClient.GuardedScript(touch, null) + ";"
                + "history.replaceState(null,'',old);const wrongDocument=" + GoogleSearchAiWebClient.GuardedScript(touch, "previous-document") + ";"
                + "report(!window.fixtureLeak && wrongPage.state==='unsafe' && wrongDocument.state==='unsafe' ? 'guarded' : 'leaked');";
        }
    }

    internal static async Task RunAsync()
    {
        foreach (string url in new[] { GoogleSearchAiWebClient.EntryUrl, "https://www.google.com/webhp?aep=11",
            "https://www.google.com/search?source=ai&udm=50" })
            if (!GoogleSearchAiWebClient.IsAiPage(url)) throw new Exception("Safe AI Mode destination rejected");
        foreach (string url in new[] { "https://www.google.com/search?q=normal", "http://www.google.com/aimode",
            "https://www.google.com:444/aimode", "https://www.google.com/search?udm=50&%75dm=50",
            "https://alice@www.google.com/aimode", "https://www.google.com.fake.invalid/aimode",
            "https://accounts.google.com/ServiceLogin", "https://consent.google.com/" })
            if (GoogleSearchAiWebClient.IsAiPage(url)) throw new Exception("Unsafe destination accepted");

        var temp = Directory.CreateTempSubdirectory("Mugonzei-SearchAI-Offline-");
        // A synthetic image bigger than one transport chunk also checks lossless chunk joining.
        using var bitmap = new Bitmap(400,400);
        var random = new Random(174);
        for (int y = 0; y < bitmap.Height; y++)
            for (int x = 0; x < bitmap.Width; x++) bitmap.SetPixel(x, y, Color.FromArgb(random.Next(0x1000000) | unchecked((int)0xff000000)));
        byte[] png = VisionImage.Prepare(bitmap);
        if (png.Length <= 192 * 1024) throw new Exception("Multi-chunk PNG fixture too small");
        Fixture active = new(Success);
        try
        {
            using var browser = new GoogleSearchAiWebClient(temp.FullName, core => Volatile.Read(ref active).Configure(core));
            foreach (string answer in new[] { Success, VisionPrompt.NoText })
            {
                var fixture = new Fixture(answer);
                Volatile.Write(ref active, fixture);
                string result = await browser.TranslateImageAsync(png, Prompt, default);
                if (answer != result || !fixture.Events.SequenceEqual(new[] { "open", "png-" + png.Length, "submit" }))
                    throw new Exception("The new document must receive the synthetic PNG and prompt once and return only this answer.");
            }
            var changedDocument = new Fixture(Success, checkScriptGuards: true);
            Volatile.Write(ref active, changedDocument);
            if (await browser.TranslateImageAsync(png, Prompt, default) != Success || !changedDocument.Events.Contains("guarded"))
                throw new Exception("Payload evaluated in a stale document or ordinary same-origin search page");

            foreach (var (url, message) in new[] {
                ("https://www.google.com/search?q=ordinary", "页面"), ("https://reject.invalid/aimode", "页面"),
                ("https://accounts.google.com/ServiceLogin", "登录"), ("https://consent.google.com/", "登录"),
                ("https://www.google.com/sorry/index", "验证") })
            {
                var fixture = new Fixture(Success, redirect: url);
                Volatile.Write(ref active, fixture);
                try { await browser.TranslateImageAsync(png, Prompt, default); throw new Exception("Rejected redirect succeeded"); }
                catch (InvalidOperationException e) when (e.Message.Contains(message, StringComparison.Ordinal)) { }
                if (!fixture.Events.Where(e => e != "redirect-get").SequenceEqual(new[] { "open" }))
                    throw new Exception($"Redirect fixture {url}: {string.Join(", ", fixture.Events)}");
            }

            Volatile.Write(ref active, new Fixture(Success, holdAnswer: true, fetchOnSubmit: "/sorry/index"));
            try { await browser.TranslateImageAsync(png, Prompt, default); throw new Exception("Embedded Google challenge ignored"); }
            catch (InvalidOperationException e) when (e.Message.Contains("验证", StringComparison.Ordinal)) { }
            Volatile.Write(ref active, new Fixture(Success, fetchOnSubmit: "/unrelated-resource"));
            if (await browser.TranslateImageAsync(png, Prompt, default) != Success) throw new Exception("Unrelated subresource counted as a challenge");

            var stalled = new Fixture(Success, holdAnswer: true);
            Volatile.Write(ref active, stalled);
            using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(20));
            var pending = browser.TranslateImageAsync(png, Prompt, cts.Token);
            await stalled.Submitted.Task.WaitAsync(cts.Token);
            cts.Cancel();
            try { await pending; throw new Exception("Cancelled answer accepted"); }
            catch (OperationCanceledException) when (cts.IsCancellationRequested) { }
            Volatile.Write(ref active, new Fixture("Recovered"));
            if (await browser.TranslateImageAsync(png, Prompt, default) != "Recovered"
                || stalled.Events.Count(x => x == "submit") != 1) throw new Exception("Cancelled turn blocked or repeated the following turn.");
        }
        finally
        {
            for (int i=0; i<20; i++)
            {
                try { temp.Delete(true); break; }
                catch (IOException) { await Task.Delay(150); }
                catch (UnauthorizedAccessException) { await Task.Delay(150); }
            }
        }
        Console.WriteLine("PASS offline WebView2 Google AI Mode destination rejection, fresh file, single submit, raw no-text, cancellation and recovery");
    }
}
